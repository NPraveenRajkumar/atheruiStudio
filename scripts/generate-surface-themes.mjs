// Builds src/surface-themes.css.
// The library only redefines ~40 variables under [data-theme=light], so a light preview surface nested inside a dark
// page inherits the dark page's values for everything else (text turns light-grey on white, primary buttons change
// colour, ...). This file defines the COMPLETE light and dark variable sets for any nested element carrying data-theme.
import fs from 'fs';

const css = fs.readFileSync('public/exploration-project-tailwind/exploration-project-tailwind.css', 'utf8');
const blocks = [...css.matchAll(/([^{}]*)\{([^{}]*--[a-z][^{}]*)\}/g)].map((m) => ({ selector: m[1].trim(), body: m[2] }));
const parse = (body) => Object.fromEntries([...body.matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)].map((m) => [m[1], m[2].trim()]));
const size = (b) => Object.keys(parse(b.body)).length;

const root = blocks.find((b) => b.selector.endsWith(':root') && size(b) > 150);
const light = { ...parse(root.body) };
for (const b of blocks) if (/\[data-theme=light\]/.test(b.selector) && !/\[data-theme="?light"?\]\s*\[/.test(b.selector)) Object.assign(light, parse(b.body));

// The library's light block writes things like `--bg-secondary: var(--bg-secondary, #f8fafc)` (meant to inherit from
// :root). Nested inside a dark page that inherits the dark value, and a self-reference is invalid CSS anyway,
// so such entries are replaced by the :root value.
const base = parse(root.body);
for (const [k, v] of Object.entries(light)) {
  const m = v.match(/^var\(\s*(--[\w-]+)\s*(?:,\s*(.+))?\)$/);
  if (m && m[1] === k) light[k] = base[k] ?? (m[2] ?? '').trim();
}

const dark = { ...light };
for (const b of blocks) if (/dark/.test(b.selector) && !/^\[data-theme="dark"\]\s*\[/.test(b.selector)) Object.assign(dark, parse(b.body));

const emit = (sel, vars) => `${sel} {\n  color-scheme: ${sel.includes('light') ? 'light' : 'dark'};\n${Object.entries(vars).map(([k, v]) => `  ${k}: ${v};`).join('\n')}\n}`;

const out = `/* Generated by scripts/generate-surface-themes.mjs. Do not edit by hand. */
${emit('[data-theme="light"]:not(html):not(body)', light)}

${emit('[data-theme="dark"]:not(html):not(body)', dark)}
`;
fs.writeFileSync('src/surface-themes.css', out);
console.log(Object.keys(light).length, 'light vars,', Object.keys(dark).length, 'dark vars');
