// Builds src/demo-dark.css: repairs for demo markup that was written for a light page.
// The demos use var(--accent-green-soft, #f0fdf4) style fallbacks (the library defines no --accent-* variables at all)
// and plain hex colours in inline styles, so on the dark preview surface they show bright panels with dark text.
// Run with: npm run demo-dark
import fs from 'node:fs';

const S = ".demo-scope[data-theme='dark']";

// 1. Accent variables: soft panel tint + a readable text tone for each hue
const accents = {
  green: ['34, 197, 94', '#4ade80'],
  blue: ['59, 130, 246', '#60a5fa'],
  yellow: ['245, 158, 11', '#fbbf24'],
  red: ['239, 68, 68', '#f87171'],
  purple: ['168, 85, 247', '#c084fc'],
  pink: ['236, 72, 153', '#f472b6'],
  indigo: ['99, 102, 241', '#818cf8'],
  cyan: ['6, 182, 212', '#22d3ee'],
  orange: ['249, 115, 22', '#fb923c'],
};
const vars = Object.entries(accents)
  .map(([n, [rgb, text]]) => `  --accent-${n}: ${text};\n  --accent-${n}-soft: rgba(${rgb}, 0.15);`)
  .join('\n');

// 2. Inline light panel backgrounds -> a faint tint. Only padded boxes, so small white swatches stay white.
const lightBgs = ['#fff', '#ffffff', 'white', '#fafafa', '#f8fafc', '#f1f5f9', '#f9fafb', '#f0f9ff', '#fff1f2', '#fef3c7', '#fefce8', '#fff7ed', '#f0fdf4', '#eff6ff', '#fee2e2', '#f5f3ff', '#fdf4ff', '#ecfdf5'];
const props = ['background', 'background-color'];
const bgSel = lightBgs
  .flatMap((v) => props.flatMap((p) => [`[style*='${p}:${v}']`, `[style*='${p}: ${v}']`]))
  .map((s) => `${S} div[style*='padding']${s}`)
  .join(',\n');

// 3. Dark text colours written for those panels -> the matching light tone
const textMap = {
  '#4ade80': ['#166534', '#15803d', '#134e4a', '#0f766e', '#047857'],
  '#60a5fa': ['#1e40af', '#1d4ed8', '#1e3a8a', '#0369a1'],
  '#fbbf24': ['#92400e', '#b45309', '#854d0e', '#9a3412', '#c2410c', '#78350f'],
  '#c084fc': ['#6b21a8', '#7e22ce', '#581c87'],
  '#f87171': ['#991b1b', '#b91c1c', '#7f1d1d'],
  'var(--text-primary)': ['#0f172a', '#1e293b', '#111827', '#1f2937'],
  'var(--text-secondary)': ['#475569', '#334155', '#4b5563', '#374151'],
};
const textRules = Object.entries(textMap)
  .map(([to, froms]) => `${froms.flatMap((c) => [`${S} [style*='color:${c}']`, `${S} [style*='color: ${c}']`]).join(',\n')} {\n  color: ${to} !important;\n}`)
  .join('\n\n');

const css = `/* Generated by scripts/generate-demo-dark.mjs. Do not edit by hand. */

${S} {
${vars}
}

/* Demo stylesheet panels that hard-code white */
${S} .playground-preview {
  background-color: color-mix(in srgb, #fff 4%, transparent);
  background-image: none;
  border-color: var(--border-default);
  box-shadow: none;
}
${S} .playground-settings {
  background-color: color-mix(in srgb, #fff 5%, transparent);
  border-color: var(--border-default);
  box-shadow: none;
}
${S} .demo-controls-wrapper {
  background: color-mix(in srgb, #fff 5%, transparent);
  border-color: var(--border-default);
}

/* Inline light panels */
${bgSel} {
  background: color-mix(in srgb, #fff 6%, transparent) !important;
  border-color: var(--border-default) !important;
}

/* Inline dark text */
${textRules}
`;
fs.writeFileSync('src/demo-dark.css', css);
console.log(`src/demo-dark.css written (${css.split('\n').length} lines)`);
