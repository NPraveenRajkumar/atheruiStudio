// Builds src/theme-light.css.
// The app is written with dark-mode Tailwind classes (bg-black, text-white, border-slate-800, text-sky-300 ...).
// Instead of rewriting every class, the light theme re-maps Tailwind's colour variables:
//   - grey scales are mirrored (950 <-> 50, 900 <-> 100, ... 600 <-> 400) so dark surfaces become light
//   - accent scales are mirrored the same way so pale-on-dark text (sky-300) becomes dark-on-light (sky-700)
//   - black and white swap
import fs from 'fs';

const theme = fs.readFileSync('node_modules/tailwindcss/theme.css', 'utf8');
const vars = Object.fromEntries([...theme.matchAll(/(--color-[a-z]+-\d+)\s*:\s*([^;]+);/g)].map((m) => [m[1], m[2].trim()]));

const GREYS = ['slate', 'gray', 'zinc', 'neutral', 'stone'];
const ACCENTS = ['red', 'orange', 'amber', 'yellow', 'lime', 'green', 'emerald', 'teal', 'cyan', 'sky', 'blue', 'indigo', 'violet', 'purple', 'fuchsia', 'pink', 'rose'];
const STEPS = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];
const mirror = (s) => STEPS[STEPS.length - 1 - STEPS.indexOf(s)];

const lines = [];
for (const fam of [...GREYS, ...ACCENTS]) {
  for (const step of STEPS) {
    const from = vars[`--color-${fam}-${mirror(step)}`];
    if (from) lines.push(`  --color-${fam}-${step}: ${from};`);
  }
}

const css = `/* Generated by scripts/generate-light-theme.mjs. Do not edit by hand. */
html.light {
  color-scheme: light;
  --color-black: #ffffff;
  --color-white: #0b1220;
${lines.join('\n')}
}
`;
fs.writeFileSync('src/theme-light.css', css);
console.log(lines.length, 'variables');
