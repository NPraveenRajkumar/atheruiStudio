// Builds src/data/designTokens.ts from the CSS custom properties that the component library really defines.
// Values are the dark-theme values (the library's :root block overridden by its dark theme blocks).
import fs from 'fs';

const css = fs.readFileSync('public/exploration-project-tailwind/exploration-project-tailwind.css', 'utf8');

const blocks = [...css.matchAll(/([^{}]*)\{([^{}]*--[a-z][^{}]*)\}/g)].map((m) => ({
  selector: m[1].trim(),
  body: m[2],
}));
const parse = (body) => Object.fromEntries([...body.matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)].map((m) => [m[1], m[2].trim()]));
const count = (b) => Object.keys(parse(b.body)).length;

const root = blocks.find((b) => b.selector.endsWith(':root') && count(b) > 150);
const darkBlocks = blocks.filter((b) => /dark/.test(b.selector) && !/^\[data-theme="dark"\]\s*\[/.test(b.selector));
const values = parse(root.body);
for (const b of darkBlocks) Object.assign(values, parse(b.body));

const isColor = (v) => /^(#|rgb|hsl)/i.test(v) && !v.includes('var(');
const pretty = (name) =>
  name
    .replace(/^--(ui-)?/, '')
    .split('-')
    .map((w) => w[0].toUpperCase() + w.slice(1))
    .join(' ');
const component = (name) => name.replace(/^--(ui-)?/, '').split('-')[0];

const entries = Object.entries(values).filter(([n]) => !n.endsWith('-rgb'));
const make = (name, value, description) => ({
  name: pretty(name),
  value,
  cssVar: name,
  description,
  previewType: isColor(value) ? 'color' : /radius/.test(name) ? 'radius' : 'text',
});

const group = (test, description) => entries.filter(([n]) => test(n)).map(([n, v]) => make(n, v, description(n)));

const categories = [
  {
    id: 'colors',
    name: 'Brand & Status Colors',
    description: 'Semantic colors used for primary actions and status feedback across every component.',
    tokens: group((n) => n.startsWith('--color-'), (n) => `Semantic color token ${n}.`),
  },
  {
    id: 'surfaces',
    name: 'Surfaces & Text',
    description: 'Background layers and text colors that switch with the active theme.',
    tokens: group(
      (n) => /^--(bg|text|label)-/.test(n),
      (n) => (n.startsWith('--bg-') ? 'Background layer.' : 'Text or label color.')
    ),
  },
  {
    id: 'borders',
    name: 'Borders',
    description: 'Divider and outline colors shared by components.',
    tokens: group((n) => n.startsWith('--border-'), () => 'Border color.'),
  },
  {
    id: 'typography',
    name: 'Typography & Shape',
    description: 'Font family and the shared button sizing tokens.',
    tokens: group((n) => n === '--font-family' || /^--(ui-)?button-/.test(n), () => 'Typography or shape token.'),
  },
  {
    id: 'components',
    name: 'Component Tokens',
    description: 'Per-component overrides. Set any of these on a parent element to restyle a single component family.',
    tokens: entries
      .filter(([n]) => !/^--(color|bg|text|label|border)-/.test(n) && n !== '--font-family' && !/^--(ui-)?button-/.test(n))
      .map(([n, v]) => make(n, v, `Used by ${component(n)} components.`)),
  },
].filter((c) => c.tokens.length);

const out = `export interface TokenCategory {
  id: string;
  name: string;
  description: string;
  tokens: {
    name: string;
    value: string;
    cssVar: string;
    description: string;
    previewType: 'color' | 'text' | 'spacing' | 'radius' | 'shadow' | 'timing';
  }[];
}

// Generated by scripts/generate-design-tokens.mjs from the library CSS (dark theme values).
export const DESIGN_TOKENS: TokenCategory[] = ${JSON.stringify(categories, null, 2)};
`;
fs.writeFileSync('src/data/designTokens.ts', out);
